#!/usr/bin/env python3
"""Hot-inject freshly built bsm binaries and units into a running live VM.

usage: tests/bsm-vm-inject.py stage [--out DIR] [--build host|container|none] [--shell] [--probe] [--seatd PATH]
       tests/bsm-vm-inject.py status

The live ISO takes over an hour to rebuild. `stage` builds the bsm crates and
lays out the files the `bsm` package installs (by running that PKGBUILD's own
`package()` function, so the staged tree cannot drift from the package) under
DIR/root (default /tmp/bsm-vm/inject). tests/bsm-qemu.py --inject DIR shares DIR
with the guest over virtio-9p (`-virtfs`, mount tag `bsminject`) and runs
DIR/apply.sh in the guest: it copies the tree over the live root (the live root
is an overlay, so nothing persists), creates the accounts and directories,
reloads D-Bus and polkit, then stops greetd and starts bsm. `status` lists what
a stage found.

Limits, read before trusting a result:

- Host builds link the Fedora host's libraries. The Arch guest must provide the
  same sonames (glibc at least as new as the host's, libwayland, libseat,
  libinput, libgbm, libxkbcommon, libudev, libpipewire-0.3, libei). `stage`
  checks `ldd` against the host only; the guest check is `ldd` run by apply.sh,
  which prints every missing library. Use `--build container` to compile inside
  an Arch Linux container instead (same libraries as the image, needs podman and
  the network once).
- Gnoblin is NOT injected: hosted mode (`gnoblin --hosted`) lives in the Gnoblin
  build, which only the image rebuild produces. Until then the scenario steps
  that need a hosted Gnoblin report `blocked`.
- The Bingux shell's QML travels in /usr/lib/bingux/bingux-shell.sxa. `--shell`
  packs shell/bingux into a new archive (scripts/pack-shell.py) and installs it,
  which is enough for QML-only changes of the greeter; C++ plugin changes need
  the image rebuild.
- Images built before bsm have no seatd; `--seatd PATH` installs one (it needs only libc).
- Nothing here is part of any package. It is a test accelerator.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = Path(os.environ.get("BSM_INJECT_DIR", "/tmp/bsm-vm/inject"))
TARGET_DIR = Path(os.environ.get("BSM_PACKAGING_TARGET", "/tmp/bsm-target/packaging"))
CONTAINER_IMAGE = "localhost/bsm-arch-build"
PKGBUILD = ROOT / "distro/packages/bsm/PKGBUILD"
# The plain cargo, not a caching wrapper: builds go to /tmp, never into the home directory.
CARGO = os.environ.get("CARGO") or (str(Path.home() / ".cargo/bin/cargo") if (Path.home() / ".cargo/bin/cargo").exists() else "cargo")

# Crates in the order the PKGBUILD builds them, with the binaries each provides.
CRATES = {
    "bsm": ["bsm", "bsmctl"],
    "bsm-helper": ["bsm-helper"],
    "bsm-host": ["bsm-host"],
    "bsm-appearance": ["bsm-imgconv"],
}

CONTAINERFILE = """\
FROM docker.io/library/archlinux:latest
RUN pacman -Syu --noconfirm --needed base-devel cargo clang pkgconf seatd libinput libdrm mesa \\
    libxkbcommon systemd-libs wayland pam libpipewire libei dbus && pacman -Scc --noconfirm
"""

APPLY = r"""#!/bin/sh
# Run in the guest as root by tests/bsm-qemu.py. Generated by tests/bsm-vm-inject.py.
# usage: apply.sh [--no-start]
set -eu
mnt=/mnt/bsm-inject
mkdir -p "$mnt"
if ! mountpoint -q "$mnt"; then
    modprobe 9pnet_virtio 2>/dev/null || true
    modprobe 9p 2>/dev/null || true
    mount -t 9p -o trans=virtio,version=9p2000.L,ro bsminject "$mnt"
fi
# The live root is an overlay with a small copy-on-write space; fail loudly when it fills.
tar -C "$mnt/root" -cf - . | tar -C / -xpf - --no-same-owner
if [ -d "$mnt/image" ]; then
    mkdir -p /etc/systemd/system
    tar -C "$mnt/image" -cf - . | tar -C /etc/systemd/system -xpf - --no-same-owner
fi
if [ -f "$mnt/bingux-shell.sxa" ]; then
    install -m 0644 "$mnt/bingux-shell.sxa" /usr/lib/bingux/bingux-shell.sxa
fi
systemd-sysusers
systemd-tmpfiles --create
systemctl daemon-reload
systemctl reload dbus-broker.service 2>/dev/null || systemctl reload dbus.service 2>/dev/null || true
systemctl reload polkit.service 2>/dev/null || true
# Every shared library the injected binaries need must exist in this guest.
missing=0
for exe in /usr/bin/bsm /usr/bin/bsmctl /usr/libexec/bsm/bsm-helper /usr/libexec/bsm/bsm-host /usr/libexec/bsm/bsm-imgconv; do
    [ -x "$exe" ] || continue
    if out="$(ldd "$exe" 2>&1 | grep -E 'not found|version .* not found')"; then
        echo "INJECT-MISSING-LIBS $exe: $out"
        missing=1
    fi
done
echo "INJECT-LIBS-OK=$((1 - missing))"
if [ "${1:-}" != "--no-start" ]; then
    # The cutover the image does with a kernel parameter: greetd off, bsm on.
    systemctl stop greetd.service 2>/dev/null || true
    # unit changes of seatd apply only when it restarts; bsm holds it, so stop bsm first
    systemctl stop bsm.service 2>/dev/null || true
    systemctl restart bsm-seatd.service
    systemctl reset-failed bsm.service bsm-seatd.service 2>/dev/null || true
    systemctl start bsm-helper.socket
    # restart: on an image that already boots bsm the old binary is still running.
    systemctl restart bsm.service || echo "INJECT-BSM-START-FAILED"
fi
echo INJECT-DONE
"""


def run(command, **kwargs):
    print("+ " + " ".join(str(part) for part in command), flush=True)
    return subprocess.run(command, check=True, **kwargs)


def present_crates():
    return [name for name in CRATES if (ROOT / "packages" / name / "Cargo.toml").is_file()]


def host_env():
    """Cargo environment: private target dir, and the system libclang for the bindgen crates.

    A developer shell may export LIBCLANG_PATH for another toolchain (an ESP clang that
    targets riscv32 makes libspa-sys fail with "__float128 is not supported"); bsm-host
    needs the host's own libclang. BSM_LIBCLANG_PATH overrides the location.
    """
    env = dict(os.environ, CARGO_TARGET_DIR=str(TARGET_DIR))
    libclang = os.environ.get("BSM_LIBCLANG_PATH")
    if libclang is None:
        libclang = next((d for d in ("/usr/lib64", "/usr/lib") if list(Path(d).glob("libclang.so*"))), None)
    if libclang:
        env["LIBCLANG_PATH"] = libclang
    return env


def build_host(crates):
    """Build each crate; one that does not compile is reported and left out, not fatal."""
    env = host_env()
    failed = []
    for name in crates:
        command = [CARGO, "build", "--release", "--manifest-path", str(ROOT / "packages" / name / "Cargo.toml")]
        print("+ " + " ".join(command), flush=True)
        if subprocess.run(command, env=env).returncode != 0:
            failed.append(name)
    return failed


def build_container(crates):
    if subprocess.run(["podman", "image", "exists", CONTAINER_IMAGE]).returncode != 0:
        build_dir = Path("/tmp/bsm-vm/container")
        build_dir.mkdir(parents=True, exist_ok=True)
        (build_dir / "Containerfile").write_text(CONTAINERFILE)
        run(["podman", "build", "-t", CONTAINER_IMAGE, str(build_dir)])
    cargo_home = Path("/tmp/bsm-vm/cargo-home")
    cargo_home.mkdir(parents=True, exist_ok=True)
    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    script = " && ".join(
        f"cargo build --release --manifest-path /src/packages/{name}/Cargo.toml" for name in crates
    )
    run(
        [
            "podman", "run", "--rm", "--security-opt", "label=disable",
            "-v", f"{ROOT}:/src:ro", "-v", f"{TARGET_DIR}:/target", "-v", f"{cargo_home}:/cargo",
            "-e", "CARGO_TARGET_DIR=/target", "-e", "CARGO_HOME=/cargo",
            CONTAINER_IMAGE, "bash", "-c", script,
        ]
    )


def run_package(out, target):
    """Run PKGBUILD's package() into out/root with srcdir pointing at this checkout and `target` as its cargo target dir."""
    work = out / "work"
    shutil.rmtree(work, ignore_errors=True)
    (work / "src").mkdir(parents=True)
    root = out / "root"
    shutil.rmtree(root, ignore_errors=True)
    root.mkdir(parents=True)
    pkgver = "0.1.0"
    (work / "src" / f"bingux-{pkgver}").symlink_to(ROOT)
    (work / "src" / "target").symlink_to(target)
    script = (
        "set -euo pipefail\n"
        f'source "{PKGBUILD}"\n'
        f'srcdir="{work / "src"}"\n'
        f'pkgdir="{root}"\n'
        "package\n"
    )
    run(["bash", "-c", script])


def stage(arguments):
    out = Path(arguments.out)
    out.mkdir(parents=True, exist_ok=True)
    crates = present_crates()
    missing = [name for name in CRATES if name not in crates]
    failed_crates = []
    if arguments.build == "host":
        failed_crates = build_host(crates)
    elif arguments.build == "container":
        build_container(crates)
    produced = {}
    for name in crates:
        for binary in CRATES[name]:
            path = TARGET_DIR / "release" / binary
            produced[binary] = path.is_file() and name not in failed_crates
    absent = sorted(binary for binary, ok in produced.items() if not ok)
    for name in missing:
        absent += [f"{binary} (crate {name} has no Cargo.toml yet)" for binary in CRATES[name]]
    if absent:
        # package() installs every binary; stub the absent ones out of the stage rather
        # than failing, and say so, so a partial tree is still useful for the harness.
        print("not built: " + ", ".join(absent))
    # package() `install`s every binary; give absent ones a placeholder in a private copy of target/release.
    private = out / "target-stage"
    (private / "release").mkdir(parents=True, exist_ok=True)
    for binary in [b for bins in CRATES.values() for b in bins]:
        real = TARGET_DIR / "release" / binary
        link = private / "release" / binary
        link.unlink(missing_ok=True)
        if produced.get(binary):
            link.symlink_to(real)
        else:
            link.write_text("#!/bin/sh\necho 'bsm-vm-inject: this binary was not built' >&2\nexit 127\n")
            link.chmod(0o755)
    run_package(out, private)
    image = out / "image"
    shutil.rmtree(image, ignore_errors=True)
    shutil.copytree(ROOT / "packaging/bsm/image", image, symlinks=True)
    if arguments.probe:
        # The root checks of tests/bsm-helper-root.sh drive this example binary in the guest.
        command = [CARGO, "build", "--release", "--examples", "--manifest-path", str(ROOT / "packages/bsm-helper/Cargo.toml")]
        run(command, env=host_env())
        probe = TARGET_DIR / "release/examples/bsm-helper-probe"
        if probe.is_file():
            destination = out / "root/usr/libexec/bsm/bsm-helper-probe"
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(probe, destination)
            destination.chmod(0o755)
    if arguments.seatd:
        # The 2026.10.24 image predates the seatd package; bsm-seatd.service needs the binary.
        destination = out / "root/usr/bin/seatd"
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(arguments.seatd, destination)
        destination.chmod(0o755)
    sxa = out / "bingux-shell.sxa"
    sxa.unlink(missing_ok=True)
    if arguments.shell:
        run([sys.executable, str(ROOT / "scripts/pack-shell.py"), str(sxa)])
    apply = out / "apply.sh"
    apply.write_text(APPLY)
    apply.chmod(0o755)
    manifest = {
        "build": arguments.build,
        "built": sorted(binary for binary, ok in produced.items() if ok),
        "not_built": absent,
        "crates_failed_to_build": failed_crates,
        "shell_archive": arguments.shell,
        "files": sorted(str(p.relative_to(out / "root")) for p in (out / "root").rglob("*") if p.is_file()),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"staged {len(manifest['files'])} files in {out}; built: {', '.join(manifest['built']) or 'nothing'}")
    return 0


def status(arguments):
    out = Path(arguments.out)
    manifest = out / "manifest.json"
    if not manifest.is_file():
        print(f"no stage at {out}; run: tests/bsm-vm-inject.py stage")
        return 1
    data = json.loads(manifest.read_text())
    print(json.dumps({k: v for k, v in data.items() if k != "files"}, indent=2))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    stage_parser = commands.add_parser("stage", help="build and lay out the injection tree")
    stage_parser.add_argument("--out", default=str(DEFAULT_OUT))
    stage_parser.add_argument("--build", choices=["host", "container", "none"], default="host")
    stage_parser.add_argument("--shell", action="store_true", help="also pack shell/bingux into a new bingux-shell.sxa")
    stage_parser.add_argument("--probe", action="store_true", help="also install the bsm-helper-probe example (root checks)")
    stage_parser.add_argument("--seatd", help="seatd binary to install as /usr/bin/seatd (images built before bsm lack it)")
    stage_parser.set_defaults(func=stage)
    status_parser = commands.add_parser("status", help="show what the last stage contains")
    status_parser.add_argument("--out", default=str(DEFAULT_OUT))
    status_parser.set_defaults(func=status)
    arguments = parser.parse_args()
    return arguments.func(arguments)


if __name__ == "__main__":
    sys.exit(main())
