#!/usr/bin/env python3
"""Generate Bingux's symbolic icon lookup from the pinned Adwaita theme."""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / "subprojects/adwaita-icon-theme/Adwaita/symbolic"
OUTPUT = ROOT / "shell/bingux/AdwaitaIconIndex.js"
ALIASES = {
    "battery-low": "battery-low-symbolic",
    "screencast-stop-symbolic": "media-playback-stop-symbolic",
    "transform-move-symbolic": "object-select-symbolic",
}


def render():
    if not THEME.is_dir():
        raise ValueError("Adwaita icon theme submodule is missing; run git submodule update --init")
    index = THEME.parents[1] / "index.theme"
    directories = next(
        (line.partition("=")[2] for line in index.read_text().splitlines() if line.startswith("Directories=")),
        "",
    )
    priority = {
        directory.split("/", 1)[1]: rank
        for rank, directory in enumerate(directories.split(","))
        if directory.startswith("symbolic/")
    }
    paths = {}
    ranks = {}
    for icon in sorted(THEME.rglob("*.svg")):
        name = icon.stem
        relative = icon.relative_to(THEME).as_posix()
        rank = priority.get(icon.parent.name, len(priority))
        if name not in paths or rank < ranks[name]:
            paths[name] = relative
            ranks[name] = rank
    if not paths:
        raise ValueError("Adwaita symbolic icon directory contains no SVG assets")
    missing = sorted(
        {
            name
            for path in (ROOT / "shell/bingux").rglob("*")
            if path.suffix in (".qml", ".js")
            for name in re.findall(r"[\"']([^\"']+-symbolic)[\"']", path.read_text(errors="replace"))
            if ALIASES.get(name, name) not in paths
        }
    )
    if missing:
        raise ValueError("symbolic icon names have no Adwaita asset or alias: " + ", ".join(missing))

    def literal(table):
        # Prettier keeps a trailing comma, so emit it and the file stays formatted.
        text = json.dumps(table, ensure_ascii=False, indent=4, sort_keys=True)
        return text[: text.rindex("\n}")] + ",\n}"

    aliases = literal(ALIASES)
    body = literal(paths)
    return (
        "// Generated by scripts/generate-adwaita-icon-index.py; do not edit.\n.pragma library\n"
        + "var aliases = "
        + aliases
        + ";\nvar paths = "
        + body
        + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in index is stale")
    args = parser.parse_args()
    try:
        expected = render()
    except ValueError as error:
        parser.error(str(error))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches the pinned Adwaita icons and all literal shell references")
        return 0
    OUTPUT.write_text(expected)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
