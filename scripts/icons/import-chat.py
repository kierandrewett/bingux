#!/usr/bin/env python3
"""Vendor the ~/dev/chat icon fork's geometry that the icon sources use.

Sources in scripts/icons/src/ pull fork icons with `<fork name="Power" weight="fill"/>`.
This script reads every `src/generated/<Name>.ts` of the chat icon package (`@chat/icons`,
a rounded fork of Phosphor with continuous corners; its custom icons such as ChatCompose
live in the same folder) and writes packages/bingux-ui/icons/chat/geometry.json: the 256 unit outlines of the
regular, fill and bold weights of ALL of them, not only the ones in use, so that any fork
icon can be chosen in labels.tsv, shown in the catalogue (`ChatIcon`), and built by
build.py without a checkout of ~/dev/chat. Output is deterministic. It fails when an
icon the sources use is missing from the chat package.

Usage:
  import-chat.py [--chat ~/dev/chat]          rewrite chat/geometry.json and src/chat_icon_list.rs
  import-chat.py --check [--chat ~/dev/chat]  fail if it differs from the chat package
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
REPO = HERE.parents[1]
OUT = REPO / "packages/bingux-ui/icons/chat/geometry.json"
CATALOGUE_RS = REPO / "packages/bingux-ui/src/chat_icon_list.rs"
FORK = re.compile(r"""<fork\b[^>]*\bname\s*=\s*["']([A-Za-z0-9]+)["']""")
WEIGHTS = ("regular", "fill", "bold")


def used_names(src_dir: Path) -> list[str]:
    names: set[str] = set()
    for src in sorted(src_dir.glob("*.svg")):
        names.update(FORK.findall(src.read_text()))
    return sorted(names)


def all_names(generated: Path) -> list[str]:
    return sorted(path.stem for path in generated.glob("*.ts"))


def read_icon(generated: Path, name: str) -> dict[str, list[str]]:
    path = generated / f"{name}.ts"
    if not path.is_file():
        raise SystemExit(f"import-chat: {name}: {path} does not exist")
    text = path.read_text()
    icon: dict[str, list[str]] = {}
    for weight in WEIGHTS:
        match = re.search(weight + r":\s*\[(.*?)\],", text, re.S)
        if match:
            icon[weight] = re.findall(r'"([^"]+)"', match.group(1))
    if "regular" not in icon:
        raise SystemExit(f"import-chat: {name}: no regular weight in {path}")
    return icon


def build(chat: Path, src_dir: Path) -> str:
    package = chat / "packages/icons"
    generated = package / "src/generated"
    if not generated.is_dir():
        raise SystemExit(f"import-chat: {generated} not found; pass --chat")
    header = (generated / "Power.ts").read_text().splitlines()[0]
    upstream = re.search(r"from (@phosphor-icons/core [0-9.]+)", header)
    try:
        commit = subprocess.run(
            ["git", "-C", str(chat), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    names = all_names(generated)
    missing = sorted(set(used_names(src_dir)) - set(names))
    if missing:
        raise SystemExit(f"import-chat: the sources use fork icons the chat package lacks: {', '.join(missing)}")
    data = {
        "source": "@chat/icons (packages/icons in the chat repository), a rounded fork of Phosphor Icons (MIT)",
        "upstream": upstream.group(1) if upstream else "unknown",
        "chat-commit": commit,
        "grid": 256,
        "icons": {name: read_icon(generated, name) for name in names},
    }
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


def catalogue_rs(geometry_text: str) -> str:
    """The `ChatIcon` enum of bingux-ui's chat-icons feature: one variant per vendored icon."""
    names = sorted(json.loads(geometry_text)["icons"])
    variants = "".join(f"    {name},\n" for name in names)
    listed = "".join(f"        ChatIcon::{name},\n" for name in names)
    texts = "".join(f'        "{name}",\n' for name in names)
    return (
        "// Generated by scripts/icons/import-chat.py from the chat icon fork; do not edit.\n"
        "\n"
        "/// Every icon of the chat fork (`@chat/icons`), named as there.\n"
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\n"
        "pub enum ChatIcon {\n"
        f"{variants}"
        "}\n"
        "\n"
        "impl ChatIcon {\n"
        "    /// Every fork icon, in alphabetical order.\n"
        f"    pub const ALL: [ChatIcon; {len(names)}] = [\n"
        f"{listed}"
        "    ];\n"
        "\n"
        "    /// The fork's name for the icon: `\"House\"`.\n"
        "    pub const fn name(self) -> &'static str {\n"
        f"        const NAMES: [&str; {len(names)}] = [\n"
        f"{texts}"
        "        ];\n"
        "        NAMES[self as usize]\n"
        "    }\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--chat", type=Path, default=Path.home() / "dev/chat")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--src", type=Path, default=SRC, help="icon sources to scan (default scripts/icons/src)")
    parser.add_argument("--output", type=Path, default=OUT, help="geometry file to write")
    args = parser.parse_args()
    OUT_FILE = args.output
    text = build(args.chat, args.src)
    listing = catalogue_rs(text)
    if args.check:
        if not OUT_FILE.exists() or OUT_FILE.read_text() != text:
            print("import-chat: chat/geometry.json is stale; run scripts/icons/import-chat.py", file=sys.stderr)
            return 1
        if not CATALOGUE_RS.exists() or CATALOGUE_RS.read_text() != listing:
            print("import-chat: src/chat_icon_list.rs is stale; run scripts/icons/import-chat.py", file=sys.stderr)
            return 1
        print("import-chat: ok")
        return 0
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(text)
    CATALOGUE_RS.write_text(listing)
    print(f"import-chat: wrote {len(json.loads(text)['icons'])} icons to {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
