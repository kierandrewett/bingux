"""Pure partition layout, kernel command line and fstab rendering. No I/O."""

from __future__ import annotations

import re
from dataclasses import dataclass, replace

from .protocol import InstallerError

MIB = 1024 * 1024
GIB = 1024 * MIB

MIN_DISK_BYTES = 8 * GIB
ESP_BYTES = 512 * MIB
BIOS_BOOT_BYTES = 1 * MIB
BOOT_BYTES = 1 * GIB  # unencrypted /boot under BIOS with an encrypted root
ESP_LABEL = "BINGUX_ESP"
BOOT_LABEL = "BINGUX_BOOT"
HOME_LABEL = "BINGUX_HOME"
ROOT_LABEL = "BINGUX_ROOT"
LUKS_NAME = "bingux-root"
BTRFS_SUBVOLS = (("@", "/"), ("@home", "/home"))
SWAP_MAPPER = "bingux-swap"
SWAPFILE = "/swapfile"
BASE_CMDLINE = ("rw",)
DISPLAY_CMDLINE = ("splash", "quiet", "loglevel=3", "rd.udev.log_level=3",
                   "vt.global_cursor_default=0")


@dataclass(frozen=True)
class PartitionSpec:
    index: int  # 1-based GPT index
    role: str  # "esp" | "bios_boot" | "boot" | "swap" | "root"
    size_bytes: int | None  # None means "grow to fill the rest of the disk"


def check_disk_size(size_bytes: int) -> None:
    if size_bytes < MIN_DISK_BYTES:
        raise InstallerError(
            "disk_too_small",
            f"disk is {size_bytes} bytes; at least {MIN_DISK_BYTES} bytes (8 GiB) is required",
        )


def partition_layout(*, uefi: bool, size_bytes: int, encrypted: bool = False,
                     swap_partition_bytes: int = 0) -> tuple[PartitionSpec, ...]:
    """Return the GPT partitions for the disk. Root always grows to fill the disk.

    BIOS with an encrypted root gets an unencrypted ext4 /boot after the BIOS boot partition:
    GRUB reads the kernel and initramfs from it and never opens the LUKS container.
    A swap partition, when asked for, sits between the boot partitions and the root."""
    check_disk_size(size_bytes)
    first = (PartitionSpec(index=1, role="esp", size_bytes=ESP_BYTES) if uefi
             else PartitionSpec(index=1, role="bios_boot", size_bytes=BIOS_BOOT_BYTES))
    specs = [first]
    index = 2
    if not uefi and encrypted:
        specs.append(PartitionSpec(index=index, role="boot", size_bytes=BOOT_BYTES))
        index += 1
    if swap_partition_bytes:
        specs.append(PartitionSpec(index=index, role="swap", size_bytes=swap_partition_bytes))
        index += 1
    specs.append(PartitionSpec(index=index, role="root", size_bytes=None))
    return tuple(specs)


def cmdline(
    *,
    root_fs_uuid: str | None,
    luks_uuid: str | None,
    filesystem: str,
    encrypted: bool,
    kernel_args: tuple[str, ...] = (),
) -> str:
    """Build the kernel command line in the order the contract specifies."""
    parts: list[str] = list(BASE_CMDLINE)
    if encrypted:
        if not luks_uuid:
            raise ValueError("luks_uuid is required for an encrypted root")
        parts.append(f"rd.luks.name={luks_uuid}={LUKS_NAME}")
        parts.append(f"root=/dev/mapper/{LUKS_NAME}")
    else:
        if not root_fs_uuid:
            raise ValueError("root_fs_uuid is required for an unencrypted root")
        parts.append(f"root=UUID={root_fs_uuid}")
    if filesystem == "btrfs":
        parts.append("rootflags=subvol=@")
    parts.extend(DISPLAY_CMDLINE)
    parts.extend(kernel_args)
    return " ".join(parts)


def fstab(
    *,
    root_fs_uuid: str,
    filesystem: str,
    boot_uuid: str | None,
    boot_fstype: str = "vfat",
    home_uuid: str | None = None,
    home_fstype: str = "ext4",
    swap_source: str | None = None,
) -> str:
    """Render /etc/fstab. /boot only when boot_uuid is set: a vfat ESP (UEFI) or an ext4 partition
    (BIOS with encryption); /home on its own partition only when home_uuid is set, else a btrfs
    @home subvolume; swap only when swap_source is set.

    swap_source is the device column of the swap entry: a path to a swap file, a UUID=
    spec, or the mapper device of encrypted swap."""
    lines = [
        "# Generated by bingux-installer. Static filesystems and swap.",
        "# <device>\t<mount>\t<type>\t<options>\t<dump>\t<pass>",
    ]
    if filesystem == "btrfs":
        lines.append(f"UUID={root_fs_uuid}\t/\tbtrfs\tsubvol=@,defaults\t0\t0")
        if home_uuid is None:
            lines.append(f"UUID={root_fs_uuid}\t/home\tbtrfs\tsubvol=@home,defaults\t0\t0")
    elif filesystem == "xfs":
        lines.append(f"UUID={root_fs_uuid}\t/\txfs\tdefaults\t0\t0")
    else:
        lines.append(f"UUID={root_fs_uuid}\t/\text4\tdefaults\t0\t1")
    if home_uuid:
        if home_fstype not in ("ext4", "btrfs", "xfs"):
            raise ValueError(f"unsupported home filesystem {home_fstype!r}")
        lines.append(f"UUID={home_uuid}\t/home\t{home_fstype}\tdefaults\t0\t2")
    if boot_uuid:
        if boot_fstype not in ("vfat", "ext4"):
            raise ValueError(f"unsupported boot filesystem {boot_fstype!r}")
        options = "umask=0077" if boot_fstype == "vfat" else "defaults"
        lines.append(f"UUID={boot_uuid}\t/boot\t{boot_fstype}\t{options}\t0\t2")
    if swap_source:
        lines.append(f"{swap_source}\tnone\tswap\tdefaults\t0\t0")
    return "\n".join(lines) + "\n"


def crypttab(*, swap_partuuid: str) -> str:
    """crypttab for encrypted swap: a random key each boot, so the swap contents are never kept."""
    return (
        "# Generated by bingux-installer. Encrypted swap, random key each boot.\n"
        f"{SWAP_MAPPER}\tPARTUUID={swap_partuuid}\t/dev/urandom\t"
        "swap,cipher=aes-xts-plain64,size=256\n"
    )


def grub_defaults(*, cmdline_text: str) -> str:
    return (
        "# Generated by bingux-installer\n"
        'GRUB_DISTRIBUTOR="Bingux OS"\n'
        f'GRUB_CMDLINE_LINUX_DEFAULT="{cmdline_text}"\n'
        "GRUB_TIMEOUT=3\n"
        "GRUB_DISABLE_OS_PROBER=false\n"
    )


def loader_conf() -> str:
    return "default bingux.conf\ntimeout 3\n"


def loader_entry(cmdline_text: str) -> str:
    return (
        "title Bingux OS\n"
        "linux /vmlinuz-linux\n"
        "initrd /initramfs-linux.img\n"
        f"options {cmdline_text}\n"
    )


MKINITCPIO_HOOKS_BASE = ("base", "systemd", "autodetect", "microcode", "modconf", "kms",
                         "keyboard", "sd-vconsole", "block")


def mkinitcpio_hooks(*, encrypted: bool, plymouth: bool) -> tuple[str, ...]:
    hooks = list(MKINITCPIO_HOOKS_BASE)
    if plymouth:
        hooks.insert(hooks.index("kms") + 1, "plymouth")
    if encrypted:
        hooks.append("sd-encrypt")
    hooks.extend(["filesystems", "fsck"])
    return tuple(hooks)


def hooks_line(hooks: tuple[str, ...]) -> str:
    return "HOOKS=(" + " ".join(hooks) + ")"


def modules_line(modules: tuple[str, ...]) -> str:
    return "MODULES=(" + " ".join(modules) + ")"


def zram_conf() -> str:
    """zram-generator config: one compressed RAM swap device, half of RAM, capped at 4 GiB."""
    return "[zram0]\nzram-size = min(ram / 2, 4096)\ncompression-algorithm = zstd\n"


@dataclass(frozen=True)
class GptPartition:
    number: int
    start: int
    end: int
    code: str
    name: str


@dataclass(frozen=True)
class GptTable:
    """A GPT read from `sgdisk -p`. Sectors are inclusive; the usable range excludes the headers."""

    sector_size: int
    first_usable: int
    last_usable: int
    partitions: tuple[GptPartition, ...]

    def free_regions(self) -> list[tuple[int, int]]:
        """Unallocated sector ranges (start, end inclusive), in disk order."""
        regions: list[tuple[int, int]] = []
        cursor = self.first_usable
        for part in sorted(self.partitions, key=lambda p: p.start):
            if part.start > cursor:
                regions.append((cursor, part.start - 1))
            cursor = max(cursor, part.end + 1)
        if cursor <= self.last_usable:
            regions.append((cursor, self.last_usable))
        return regions

    def free_bytes(self) -> int:
        return sum(end - start + 1 for start, end in self.free_regions()) * self.sector_size


_SECTOR_SIZE_RE = re.compile(r"Sector size \(logical[^)]*\):\s*(\d+)")
_USABLE_RE = re.compile(r"First usable sector is (\d+), last usable sector is (\d+)")
_PART_ROW_RE = re.compile(r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+[\d.]+\s+\S+\s+([0-9A-Fa-f]{4})\s*(.*?)\s*$")


def parse_sgdisk_print(text: str) -> GptTable:
    """Parse `sgdisk -p DISK` output. Raises ValueError when the text is not a GPT listing."""
    sector = _SECTOR_SIZE_RE.search(text)
    usable = _USABLE_RE.search(text)
    if sector is None or usable is None:
        raise ValueError("not a GPT listing")
    parts = []
    for line in text.splitlines():
        row = _PART_ROW_RE.match(line)
        if row is not None:
            number, start, end, code, name = row.groups()
            parts.append(GptPartition(int(number), int(start), int(end), code.upper(), name))
    return GptTable(
        sector_size=int(sector.group(1)),
        first_usable=int(usable.group(1)),
        last_usable=int(usable.group(2)),
        partitions=tuple(parts),
    )


# GPT type codes. A free_space layout creates partitions with these; a reused one keeps its own.
GPT_ESP = "EF00"
GPT_BIOS_BOOT = "EF02"
GPT_LINUX = "8300"
GPT_LINUX_SWAP = "8200"
GPT_LINUX_LUKS = "8309"
GPT_MAX_ENTRIES = 128
ROOT_MIN_BYTES = 1 * GIB  # the growable root of a free_space layout is at least this large


@dataclass(frozen=True)
class FreePartition:
    """One planned partition. `action` is reuse (kept as-is, nothing written), format (existing
    partition, mkfs only) or create (new GPT entry, then mkfs). `fs` is the home filesystem."""

    role: str  # "esp" | "bios_boot" | "boot" | "swap" | "root" | "home"
    number: int  # 1-based GPT index
    start: int  # first sector, inclusive
    end: int  # last sector, inclusive
    code: str
    name: str
    action: str  # "reuse" | "format" | "create"
    fs: str = ""  # home: "ext4" | "btrfs" | "xfs" (reuse: the filesystem found on disk)


def partition_path(disk: str, number: int) -> str:
    """Device node of GPT partition `number`: /dev/vda3, /dev/nvme0n1p3."""
    return f"{disk}p{number}" if disk[-1].isdigit() else f"{disk}{number}"


def _align_up(sector: int, unit: int) -> int:
    return -(-sector // unit) * unit


def _no_free_space(largest_bytes: int, need_bytes: int) -> InstallerError:
    return InstallerError(
        "no_free_space",
        f"the largest unallocated region is {largest_bytes // MIB} MiB; "
        f"the layout needs at least {need_bytes // MIB} MiB",
    )


def free_space_layout(table: GptTable, *, uefi: bool, encrypted: bool,
                      swap_partition_bytes: int = 0) -> tuple[FreePartition, ...]:
    """Place the Bingux partitions in the largest unallocated region of an existing GPT.

    An existing ESP (UEFI) or BIOS boot partition is reused; otherwise one is created. The
    created partitions follow in disk order: boot (BIOS, encrypted), swap, root. Root takes the
    rest of the region. Raises no_free_space when the largest region cannot hold the layout.
    Pure: no I/O.
    """
    reuse_code = GPT_ESP if uefi else GPT_BIOS_BOOT
    reused = next((p for p in table.partitions if p.code == reuse_code), None)
    specs: list[tuple[str, int, str, str]] = []  # role, size bytes, code, name
    if reused is None:
        specs.append(("esp", ESP_BYTES, GPT_ESP, ESP_LABEL) if uefi
                     else ("bios_boot", BIOS_BOOT_BYTES, GPT_BIOS_BOOT, "BIOS boot"))
    if not uefi and encrypted:
        specs.append(("boot", BOOT_BYTES, GPT_LINUX, BOOT_LABEL))
    if swap_partition_bytes:
        specs.append(("swap", swap_partition_bytes, GPT_LINUX_SWAP, "bingux-swap"))
    need = sum(size for _, size, _, _ in specs) + ROOT_MIN_BYTES

    first, last = max(table.free_regions(), key=lambda r: r[1] - r[0], default=(0, -1))
    largest_bytes = (last - first + 1) * table.sector_size
    unit = max(1, MIB // table.sector_size)  # 1 MiB alignment
    used = {p.number for p in table.partitions}

    def next_number() -> int:
        for number in range(1, GPT_MAX_ENTRIES + 1):
            if number not in used:
                used.add(number)
                return number
        raise InstallerError("no_free_space", "the partition table has no free entry")

    out: list[FreePartition] = []
    if reused is not None:
        out.append(FreePartition("esp" if uefi else "bios_boot", reused.number, reused.start,
                                 reused.end, reuse_code, reused.name, action="reuse"))
    cursor = _align_up(first, unit)
    for role, size_bytes, code, name in specs:
        sectors = _align_up(-(-size_bytes // table.sector_size), unit)
        if cursor + sectors - 1 > last:
            raise _no_free_space(largest_bytes, need)
        out.append(FreePartition(role, next_number(), cursor, cursor + sectors - 1, code, name,
                                 action="create"))
        cursor += sectors
    if (last - cursor + 1) * table.sector_size < ROOT_MIN_BYTES:
        raise _no_free_space(largest_bytes, need)
    root_code = GPT_LINUX_LUKS if encrypted else GPT_LINUX
    out.append(FreePartition("root", next_number(), cursor, last, root_code, ROOT_LABEL,
                             action="create"))
    return tuple(out)


@dataclass(frozen=True)
class ManualEntry:
    """One partition of a manual layout. `number` is the GPT index the plan's device names;
    a create entry must name an index the table does not use yet."""

    number: int
    role: str
    action: str  # "reuse" | "format" | "create"
    size_bytes: int  # create only
    fs: str  # home only


CREATE_CODES = {"esp": GPT_ESP, "bios_boot": GPT_BIOS_BOOT, "boot": GPT_LINUX,
                "swap": GPT_LINUX_SWAP, "home": GPT_LINUX}
CREATE_NAMES = {"esp": ESP_LABEL, "bios_boot": "BIOS boot", "boot": BOOT_LABEL,
                "swap": "bingux-swap", "home": HOME_LABEL, "root": ROOT_LABEL}


def partition_number(disk: str, device: str) -> int | None:
    """GPT index of `device` on `disk`, the inverse of partition_path; None when it is not one."""
    match = re.fullmatch(re.escape(disk) + r"p?([0-9]+)", device)
    if match is None:
        return None
    number = int(match.group(1))
    return number if partition_path(disk, number) == device else None


def manual_layout(table: GptTable, entries: tuple[ManualEntry, ...], *,
                  encrypted: bool) -> tuple[FreePartition, ...]:
    """Map an explicit partition list onto the GPT, in list order.

    reuse and format keep an existing entry (its place, code and name). create places a new
    entry in the largest unallocated region, in list order, aligned to 1 MiB. Raises
    invalid_plan for a missing or clashing entry or a root under 1 GiB, and no_free_space when
    the new entries do not fit. Pure: no I/O.
    """
    by_number = {p.number: p for p in table.partitions}
    for e in entries:
        if e.action == "create" and e.number in by_number:
            raise InstallerError("invalid_plan",
                                 f"partition {e.number} already exists; create needs an unused one")
        if e.action != "create" and e.number not in by_number:
            raise InstallerError("invalid_plan", f"partition {e.number} is not on the disk")
        if e.action == "create" and e.role == "root" and e.size_bytes < ROOT_MIN_BYTES:
            raise InstallerError("invalid_plan", "a new root partition needs at least 1 GiB")

    creates = [e for e in entries if e.action == "create"]
    unit = max(1, MIB // table.sector_size)  # 1 MiB alignment
    sectors = {e.number: _align_up(-(-e.size_bytes // table.sector_size), unit) for e in creates}
    need = sum(sectors.values()) * table.sector_size
    first, last = max(table.free_regions(), key=lambda r: r[1] - r[0], default=(0, -1))
    largest_bytes = (last - first + 1) * table.sector_size
    placed: dict[int, tuple[int, int]] = {}
    cursor = _align_up(first, unit)
    for e in creates:
        if cursor + sectors[e.number] - 1 > last:
            raise _no_free_space(largest_bytes, need)
        placed[e.number] = (cursor, cursor + sectors[e.number] - 1)
        cursor += sectors[e.number]

    out: list[FreePartition] = []
    for e in entries:
        if e.action == "create":
            start, end = placed[e.number]
            code = GPT_LINUX_LUKS if encrypted and e.role == "root" else (
                GPT_LINUX if e.role == "root" else CREATE_CODES[e.role])
            name = CREATE_NAMES[e.role]
        else:
            existing = by_number[e.number]
            start, end, code, name = existing.start, existing.end, existing.code, existing.name
        out.append(FreePartition(e.role, e.number, start, end, code, name, action=e.action,
                                 fs=e.fs))
    return tuple(out)


def shrink_end_sector(part: GptPartition, size_bytes: int, sector_size: int) -> int:
    """Last sector of `part` once it shrinks to hold size_bytes, rounded up to a 1 MiB boundary.

    Raises cannot_shrink when that end is not before the current end: nothing would be freed.
    """
    unit = MIB // sector_size
    first_free = part.start + -(-size_bytes // sector_size)
    new_end = _align_up(first_free, unit) - 1
    if new_end >= part.end:
        raise InstallerError("cannot_shrink",
                             f"partition {part.number} cannot shrink to {size_bytes} bytes")
    return new_end


def shrink_table(table: GptTable, number: int, new_end: int) -> GptTable:
    """The table with partition `number` ending at new_end. Pure: the disk is not touched."""
    parts = tuple(replace(p, end=new_end) if p.number == number else p for p in table.partitions)
    return replace(table, partitions=parts)
