"""Pure partition layout, kernel command line and fstab rendering. No I/O."""

from __future__ import annotations

import re
from dataclasses import dataclass

from .protocol import InstallerError

MIB = 1024 * 1024
GIB = 1024 * MIB

MIN_DISK_BYTES = 8 * GIB
ESP_BYTES = 512 * MIB
BIOS_BOOT_BYTES = 1 * MIB
BOOT_BYTES = 1 * GIB  # unencrypted /boot under BIOS with an encrypted root
ESP_LABEL = "BINGUX_ESP"
BOOT_LABEL = "BINGUX_BOOT"
ROOT_LABEL = "BINGUX_ROOT"
LUKS_NAME = "bingux-root"
BTRFS_SUBVOLS = (("@", "/"), ("@home", "/home"))
SWAP_MAPPER = "bingux-swap"
SWAPFILE = "/swapfile"
BASE_CMDLINE = ("rw",)
DISPLAY_CMDLINE = ("splash", "quiet", "loglevel=3", "rd.udev.log_level=3",
                   "vt.global_cursor_default=0")


@dataclass(frozen=True)
class PartitionSpec:
    index: int  # 1-based GPT index
    role: str  # "esp" | "bios_boot" | "boot" | "swap" | "root"
    size_bytes: int | None  # None means "grow to fill the rest of the disk"


def check_disk_size(size_bytes: int) -> None:
    if size_bytes < MIN_DISK_BYTES:
        raise InstallerError(
            "disk_too_small",
            f"disk is {size_bytes} bytes; at least {MIN_DISK_BYTES} bytes (8 GiB) is required",
        )


def partition_layout(*, uefi: bool, size_bytes: int, encrypted: bool = False,
                     swap_partition_bytes: int = 0) -> tuple[PartitionSpec, ...]:
    """Return the GPT partitions for the disk. Root always grows to fill the disk.

    BIOS with an encrypted root gets an unencrypted ext4 /boot after the BIOS boot partition:
    GRUB reads the kernel and initramfs from it and never opens the LUKS container.
    A swap partition, when asked for, sits between the boot partitions and the root."""
    check_disk_size(size_bytes)
    first = (PartitionSpec(index=1, role="esp", size_bytes=ESP_BYTES) if uefi
             else PartitionSpec(index=1, role="bios_boot", size_bytes=BIOS_BOOT_BYTES))
    specs = [first]
    index = 2
    if not uefi and encrypted:
        specs.append(PartitionSpec(index=index, role="boot", size_bytes=BOOT_BYTES))
        index += 1
    if swap_partition_bytes:
        specs.append(PartitionSpec(index=index, role="swap", size_bytes=swap_partition_bytes))
        index += 1
    specs.append(PartitionSpec(index=index, role="root", size_bytes=None))
    return tuple(specs)


def cmdline(
    *,
    root_fs_uuid: str | None,
    luks_uuid: str | None,
    filesystem: str,
    encrypted: bool,
    kernel_args: tuple[str, ...] = (),
) -> str:
    """Build the kernel command line in the order the contract specifies."""
    parts: list[str] = list(BASE_CMDLINE)
    if encrypted:
        if not luks_uuid:
            raise ValueError("luks_uuid is required for an encrypted root")
        parts.append(f"rd.luks.name={luks_uuid}={LUKS_NAME}")
        parts.append(f"root=/dev/mapper/{LUKS_NAME}")
    else:
        if not root_fs_uuid:
            raise ValueError("root_fs_uuid is required for an unencrypted root")
        parts.append(f"root=UUID={root_fs_uuid}")
    if filesystem == "btrfs":
        parts.append("rootflags=subvol=@")
    parts.extend(DISPLAY_CMDLINE)
    parts.extend(kernel_args)
    return " ".join(parts)


def fstab(
    *,
    root_fs_uuid: str,
    filesystem: str,
    boot_uuid: str | None,
    boot_fstype: str = "vfat",
    swap_source: str | None = None,
) -> str:
    """Render /etc/fstab. /boot only when boot_uuid is set: a vfat ESP (UEFI) or an ext4 partition
    (BIOS with encryption); swap only when swap_source is set.

    swap_source is the device column of the swap entry: a path to a swap file, a UUID=
    spec, or the mapper device of encrypted swap."""
    lines = [
        "# Generated by bingux-installer. Static filesystems and swap.",
        "# <device>\t<mount>\t<type>\t<options>\t<dump>\t<pass>",
    ]
    if filesystem == "btrfs":
        lines.append(f"UUID={root_fs_uuid}\t/\tbtrfs\tsubvol=@,defaults\t0\t0")
        lines.append(f"UUID={root_fs_uuid}\t/home\tbtrfs\tsubvol=@home,defaults\t0\t0")
    elif filesystem == "xfs":
        lines.append(f"UUID={root_fs_uuid}\t/\txfs\tdefaults\t0\t0")
    else:
        lines.append(f"UUID={root_fs_uuid}\t/\text4\tdefaults\t0\t1")
    if boot_uuid:
        if boot_fstype not in ("vfat", "ext4"):
            raise ValueError(f"unsupported boot filesystem {boot_fstype!r}")
        options = "umask=0077" if boot_fstype == "vfat" else "defaults"
        lines.append(f"UUID={boot_uuid}\t/boot\t{boot_fstype}\t{options}\t0\t2")
    if swap_source:
        lines.append(f"{swap_source}\tnone\tswap\tdefaults\t0\t0")
    return "\n".join(lines) + "\n"


def crypttab(*, swap_partuuid: str) -> str:
    """crypttab for encrypted swap: a random key each boot, so the swap contents are never kept."""
    return (
        "# Generated by bingux-installer. Encrypted swap, random key each boot.\n"
        f"{SWAP_MAPPER}\tPARTUUID={swap_partuuid}\t/dev/urandom\t"
        "swap,cipher=aes-xts-plain64,size=256\n"
    )


def grub_defaults(*, cmdline_text: str) -> str:
    return (
        "# Generated by bingux-installer\n"
        'GRUB_DISTRIBUTOR="Bingux OS"\n'
        f'GRUB_CMDLINE_LINUX_DEFAULT="{cmdline_text}"\n'
        "GRUB_TIMEOUT=3\n"
    )


def loader_conf() -> str:
    return "default bingux.conf\ntimeout 3\n"


def loader_entry(cmdline_text: str) -> str:
    return (
        "title Bingux OS\n"
        "linux /vmlinuz-linux\n"
        "initrd /initramfs-linux.img\n"
        f"options {cmdline_text}\n"
    )


MKINITCPIO_HOOKS_BASE = ("base", "systemd", "autodetect", "microcode", "modconf", "kms",
                         "keyboard", "sd-vconsole", "block")


def mkinitcpio_hooks(*, encrypted: bool, plymouth: bool) -> tuple[str, ...]:
    hooks = list(MKINITCPIO_HOOKS_BASE)
    if plymouth:
        hooks.insert(hooks.index("kms") + 1, "plymouth")
    if encrypted:
        hooks.append("sd-encrypt")
    hooks.extend(["filesystems", "fsck"])
    return tuple(hooks)


def hooks_line(hooks: tuple[str, ...]) -> str:
    return "HOOKS=(" + " ".join(hooks) + ")"


def modules_line(modules: tuple[str, ...]) -> str:
    return "MODULES=(" + " ".join(modules) + ")"


def zram_conf() -> str:
    """zram-generator config: one compressed RAM swap device, half of RAM, capped at 4 GiB."""
    return "[zram0]\nzram-size = min(ram / 2, 4096)\ncompression-algorithm = zstd\n"


@dataclass(frozen=True)
class GptPartition:
    number: int
    start: int
    end: int
    code: str
    name: str


@dataclass(frozen=True)
class GptTable:
    """A GPT read from `sgdisk -p`. Sectors are inclusive; the usable range excludes the headers."""

    sector_size: int
    first_usable: int
    last_usable: int
    partitions: tuple[GptPartition, ...]

    def free_regions(self) -> list[tuple[int, int]]:
        """Unallocated sector ranges (start, end inclusive), in disk order."""
        regions: list[tuple[int, int]] = []
        cursor = self.first_usable
        for part in sorted(self.partitions, key=lambda p: p.start):
            if part.start > cursor:
                regions.append((cursor, part.start - 1))
            cursor = max(cursor, part.end + 1)
        if cursor <= self.last_usable:
            regions.append((cursor, self.last_usable))
        return regions

    def free_bytes(self) -> int:
        return sum(end - start + 1 for start, end in self.free_regions()) * self.sector_size


_SECTOR_SIZE_RE = re.compile(r"Sector size \(logical[^)]*\):\s*(\d+)")
_USABLE_RE = re.compile(r"First usable sector is (\d+), last usable sector is (\d+)")
_PART_ROW_RE = re.compile(r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+[\d.]+\s+\S+\s+([0-9A-Fa-f]{4})\s*(.*?)\s*$")


def parse_sgdisk_print(text: str) -> GptTable:
    """Parse `sgdisk -p DISK` output. Raises ValueError when the text is not a GPT listing."""
    sector = _SECTOR_SIZE_RE.search(text)
    usable = _USABLE_RE.search(text)
    if sector is None or usable is None:
        raise ValueError("not a GPT listing")
    parts = []
    for line in text.splitlines():
        row = _PART_ROW_RE.match(line)
        if row is not None:
            number, start, end, code, name = row.groups()
            parts.append(GptPartition(int(number), int(start), int(end), code.upper(), name))
    return GptTable(
        sector_size=int(sector.group(1)),
        first_usable=int(usable.group(1)),
        last_usable=int(usable.group(2)),
        partitions=tuple(parts),
    )
