//! The settings of each Easy Effects plugin and the port of the published plugin they drive.
//!
//! Easy Effects hosts the same plugins Bingux does and names each of its settings after a
//! port: a preset's `attack-time` is the Linux Studio Compressor's `at`. This table is that
//! mapping, taken from Easy Effects' own source (the `BIND_LV2_PORT` lines of each plugin).

/// How an Easy Effects value becomes the port's.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Conv {
    /// The same number.
    Plain,
    /// Decibels in the preset, a linear gain at the port.
    Db,
    /// A switch that means the opposite.
    Inverted,
}

