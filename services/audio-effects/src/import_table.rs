/// The settings of `plugin`.
pub fn ports(plugin: &str) -> &'static [(&'static str, &'static str, Conv)] {
    PORTS
        .iter()
        .find(|(name, _)| *name == plugin)
        .map_or(&[], |(_, ports)| ports)
}
